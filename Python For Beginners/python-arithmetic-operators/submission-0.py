# Arithmetic operators are used to perform mathematical operations like addition, subtraction, multiplication, division, and more. The result of division is always a float in Python. For the other arithmetic operators, the result will be an integer if both operands are integers. If one of the operands is a float, the result will be a float. The order of operations in Python is the same as in mathematics (PEMDAS)

a, b, c = 2, 2, 0.5
sumdig = a+b+c
print(sumdig)
print(0-sumdig)
muldig = a*b*c
print(muldig)
print(sumdig/muldig)