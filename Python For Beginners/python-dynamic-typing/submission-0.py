# In Python a single variable's type can change throughout the code. This is called dynamic typing. For example, the following code will run without any errors:
# variable = 10
# variable = "Hello"
# variable = [1, 2, 3]

variable = 10
print(type(variable))

variable = 21.5
print(type(variable))

variable = False
print(type(variable))

variable = "Hello"
print(type(variable))

variable = [3,6,9]
print(type(variable))
